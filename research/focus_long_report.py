"""Describe independent LONG-only and SHORT-only BTC trading accounts.

Consumes JSON generated by five_step_observable_backtest.py; it does not
reimplement signals, refit parameters or search for a winning model.
"""
from __future__ import annotations
import argparse
import json
from collections import defaultdict
from datetime import datetime,timezone
from pathlib import Path

FOCUS=("A_LONG_BMS","A_LONG_RTO","A_LONG_RTO_NEG",
       "B_LONG_RTO","B_LONG_RTO_NEG","B_LONG_RTO_STREAK3",
       "A_SHORT_RTO","B_SHORT_RTO","B_SHORT_RTO_POS")
SPLITS=("2022_2024","2025_2026")

def analyze(result):
    if (result.get("status")!="RESEARCH_ONLY" or
        "future" in result.get("funding_streak3_rule","").lower() or
        "three ALREADY SETTLED" not in result.get("funding_streak3_rule","")):
        raise ValueError("Study not time-safe; expected fixed funding protocol")
    by_key={f'{x["variant"]}__{x["split"]}':x for x in result["results"]}
    summaries=[]
    year_by_year=[]
    for name in FOCUS:
        for split in SPLITS:
            k=name+"__"+split
            if k not in by_key or k not in result["trades"]:
                raise ValueError("Missing independent cohort: "+k)
            row=by_key[k]
            trades=result["trades"][k]
            side=1 if "_LONG_" in name else -1
            if any(x["side"]!=side for x in trades):
                raise ValueError("A mixed-side trade entered independent cohort "+k)
            summaries.append({
                "variant":name,"split":split,"trades":row["trades"],
                "net_return_pct":row["return_pct"],
                "profit_factor":row["profit_factor"],
                "win_rate_pct":row["win_rate_pct"],
                "intratrade_dd_pct":row["max_intratrade_drawdown_pct"],
                "stops":row["stops"],"targets":row["targets"],
                "total_fee_usdt":round(sum(x["fee_cash"] for x in trades),3),
                "total_funding_usdt":round(sum(x["funding_cash"] for x in trades),3),
                "total_price_pnl_usdt":round(sum(x["price_cash"] for x in trades),3),
                "risk_rejected":row["rejected_stop_distance"],
                "unfilled_due_to_cooldown":row["overlap_or_cooldown"],
                "holding_hours":round(sum((x["exit_time"]-x["entry_time"])/3600000 for x in trades),2),
            })
            groups=defaultdict(list)
            for tr in trades:
                year=datetime.fromtimestamp(tr["entry_time"]/1000,timezone.utc).year
                groups[year].append(tr)
            for year in range(2022,2027):
                if split=="2022_2024" and year>2024 or split=="2025_2026" and year<2025:
                    continue
                subset=groups[year]
                year_by_year.append({
                    "variant":name,"split":split,"year":year,"trades":len(subset),
                    "net_pnl_usdt":round(sum(x["pnl"] for x in subset),3),
                    "funding_pnl_usdt":round(sum(x["funding_cash"] for x in subset),3),
                    "fee_usdt":round(sum(x["fee_cash"] for x in subset),3),
                    "wins":sum(x["pnl"]>0 for x in subset),
                    "stops":sum(x["type"] in ("STOP","GAP_STOP") for x in subset),
                    "targets":sum(x["type"]=="TARGET" for x in subset),
                })
    return {"status":"RESEARCH_ONLY", "source_model":result["model"],
            "sample":result["period"],"cohorts":summaries,"annual":year_by_year,
            "important_limits":[
              "Each variant uses its OWN independent hypothetical 10000 USDT account, not the old mixed-account side extraction",
              "Trading volume is low. Yearly attribution by trade entry; annual net P&L USD not annual strategy return",
              "Funding is historical settled approximated cashflow, not measured orderbook execution",
              "Adding funding changes eligibility/cooldown interactions; separate cohort returns do not estimate pure causal effects",
              "2022 first half excluded by day EMA200 warmup; 2025-26 is already inspected development data",
              "Only OHLCV + Funding observable subset, no full CVD/OI or exact v3.3/Eric parity",
              "Do not optimize based on these known historical outcomes or claim live positive expectancy"]}

def markdown(x):
    lines=["# BTC 只做多 vs 资金费率过滤｜独立账户专项研究","",
           "每个变体都以独立10,000 USDT模拟权益运行；净收益包含设定手续费、滑点和已结算Funding近似现金流。",
           "2022年年初的EMA200预热期不产生交易。后段2025—2026不是未曾检视的真正样本外。","",
           "| 模型 | 时段 | 交易数 | 净收益% | 胜率% | PF | 浮动回撤% | 止损 | 目标 | 手续费USDT | Funding USDT |",
           "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for v in x["cohorts"]:
        fmt=lambda z: "—" if z is None else str(z)
        lines.append(f"| {v['variant']} | {v['split']} | {v['trades']} | {v['net_return_pct']} | {fmt(v['win_rate_pct'])} | {fmt(v['profit_factor'])} | {v['intratrade_dd_pct']} | {v['stops']} | {v['targets']} | {v['total_fee_usdt']} | {v['total_funding_usdt']} |")
    lines+=["","## 年度分布：入场年份归因，不等于独立年度账户收益","",
            "| 变体 | 年份 | 笔数 | 胜笔 | 年内入场交易净损益（USDT） | Funding（USDT） |",
            "|---|---:|---:|---:|---:|---:|"]
    for v in x["annual"]:
        lines.append(f"| {v['variant']} | {v['year']} | {v['trades']} | {v['wins']} | {v['net_pnl_usdt']} | {v['funding_pnl_usdt']} |")
    lines+=["","## 研究解释与缺陷",*["- "+w for w in x["important_limits"]],
            "","**无论个别模型净收益是否为正，均应保持RESEARCH_ONLY。**",""]
    return "\n".join(lines)

def main():
    p=argparse.ArgumentParser()
    p.add_argument("--input",default="output/five_step/results.json")
    p.add_argument("--output-dir",default="output/long_focus")
    args=p.parse_args()
    original=json.loads(Path(args.input).read_text(encoding="utf-8"))
    doc=analyze(original)
    target=Path(args.output_dir)
    target.mkdir(parents=True,exist_ok=True)
    (target/"long_focus.json").write_text(json.dumps(doc,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
    (target/"long_focus.md").write_text(markdown(doc),encoding="utf-8")
    print(markdown(doc))

if __name__=="__main__":
    main()
